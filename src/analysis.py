def _dispatch_analysis_mode(mode):
    return {"set_encoder_attention":_attr_main,"icd_probe_attribution":_icd_main,"imputation":_imp_main,"visualize":_viz_main}[mode]

def main(argv=None):
    values=list(sys.argv[1:] if argv is None else argv)
    parser=argparse.ArgumentParser(prog="python -m src.analysis",description="Unified post-training Phase-1 analysis")
    parser.add_argument("mode",choices=MODES)
    parser.add_argument("analysis_args",nargs=argparse.REMAINDER)
    parsed=parser.parse_args(values)
    target=_dispatch_analysis_mode(parsed.mode)
    old_argv=sys.argv; sys.argv=[f"python -m src.analysis {parsed.mode}",*parsed.analysis_args]
    try: return target()
    finally: sys.argv=old_argv

if __name__ == "__main__": main()
